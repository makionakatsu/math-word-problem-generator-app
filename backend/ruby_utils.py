def get_ruby_words_count(text: str) -> int:
    """
    テキスト内のルビタグの数を返す
    
    Args:
        text: 検査するテキスト
    
    Returns:
        ルビタグの数
    """
    return text.count('<ruby>')


def remove_ruby_tags(text: str) -> str:
    """
    テキストからルビタグを除去する
    
    Args:
        text: ルビタグを含むテキスト
    
    Returns:
        ルビタグが除去されたテキスト
    """
    import re
    # <ruby>漢字<rt>よみ</rt></ruby> → 漢字
    pattern = r'<ruby>([^<]+)<rt>[^<]+</rt></ruby>'
    return re.sub(pattern, r'\1', text)