def get_topics_for_grade(grade: int) -> List[str]:
    """指定された学年の数学トピックを取得"""
    return CURRICULUM.get(grade, {}).get("topics", [])

def get_templates_for_grade(grade: int) -> List[str]:
    """指定された学年の問題テンプレートを取得"""
    return CURRICULUM.get(grade, {}).get("templates", [])

def get_problem_count_for_grade(grade: int) -> int:
    """学年に応じた問題数を返す"""
    if 1 <= grade <= 6:
        return 5  # 小学生: 5問
    elif 7 <= grade <= 9:
        return 5  # 中学生: 5問
    elif 10 <= grade <= 12:
        return 3  # 高校生: 3問
    else:
        return 1  # デフォルト